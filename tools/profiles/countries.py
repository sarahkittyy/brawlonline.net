"""Writes the profile country lists from flag-icons' country.json (docs/design/profiles.md §7):

    launcher/src/common/countries.json        what the launcher shows (code, name), by name
    server/crates/common/src/countries.rs     the same for the server, which checks codes and names the web page's

Run from the repository root after updating flag-icons in the launcher:

    python tools/profiles/countries.py

The names are flag-icons' with the short everyday form where it gives an official one (SHORT_NAMES), and
"xx" (its unknown-flag placeholder) is left out.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "launcher" / "node_modules" / "flag-icons" / "country.json"

# Sarah's board, 2026-11-09: "United States of America should just be United States".
SHORT_NAMES = {
    "us": "United States",
    "cd": "DR Congo",
    "cg": "Congo",
    "cz": "Czechia",
    "fm": "Micronesia",
    "bn": "Brunei",
    "ps": "Palestine",
    "va": "Vatican City",
    "vg": "British Virgin Islands",
    "vi": "U.S. Virgin Islands",
    "um": "U.S. Outlying Islands",
    "sh": "Saint Helena",
    "gs": "South Georgia",
    "cc": "Cocos Islands",
    "hm": "Heard and McDonald Islands",
    "bq": "Caribbean Netherlands",
    "arab": "Arab League",
    "asean": "ASEAN",
    "cefta": "CEFTA",
    "eac": "East African Community",
}


def main() -> None:
    raw = json.loads(SOURCE.read_text(encoding="utf-8"))
    countries = sorted(
        ({"code": c["code"], "name": SHORT_NAMES.get(c["code"], c["name"])} for c in raw if c["code"] != "xx"),
        key=lambda c: c["name"],
    )
    out = ROOT / "launcher" / "src" / "common" / "countries.json"
    out.write_text(json.dumps(countries, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    lines = [
        "//! Countries a profile can show (docs/design/profiles.md): every flag in flag-icons 7.6.0 (MIT, lipis/flag-icons:",
        "//! ISO 3166-1 plus regions and groups such as England, Catalonia, the EU and the UN), by its code and short name,",
        "//! sorted by name. Generated by tools/profiles/countries.py, with launcher/src/common/countries.json; not",
        "//! hand-edited.",
        "",
        "/// (code, name): the code is flag-icons' (`gb-eng`, `us`), lower case.",
        "pub const COUNTRIES: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({json.dumps(c['code'])}, {json.dumps(c['name'], ensure_ascii=False)})," for c in countries]
    lines += [
        "];",
        "",
        "/// The name of a country code, `None` for a code not in [`COUNTRIES`].",
        "pub fn country_name(code: &str) -> Option<&'static str> {",
        "    COUNTRIES.iter().find(|(c, _)| *c == code).map(|(_, n)| *n)",
        "}",
        "",
    ]
    rs = ROOT / "server" / "crates" / "common" / "src" / "countries.rs"
    rs.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(countries)} countries")


if __name__ == "__main__":
    main()
